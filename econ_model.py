def intervals_per_day(p=P):
    return 1440 / p["interval_min"]


def readings_per_month(p=P):
    return p["meters"] * intervals_per_day(p) * p["days_month"]


def annual_kwh(p=P):
    return p["area_m2"] * p["kwh_m2_year"]


def anomaly_loss_kwh(days, p=P):
    return p["delta_kw"] * p["anomaly_hours_day"] * days * p["anomalies_month"] * 12


def value_model(p=P):
    loss_as_is = anomaly_loss_kwh(p["days_as_is"], p)
    loss_to_be = anomaly_loss_kwh(p["days_to_be"], p)
    saved_kwh = sub(loss_as_is, loss_to_be)
    energy_eur = saved_kwh * p["tariff"]
    labor_eur = sub(p["tech_hours_as_is"], p["tech_hours_to_be"]) * p["anomalies_month"] * 12 * p["tech_rate"]
    total = energy_eur + labor_eur
    return {
        "annual_kwh": annual_kwh(p),
        "annual_cost": annual_kwh(p) * p["tariff"],
        "loss_as_is_kwh": loss_as_is,
        "loss_to_be_kwh": loss_to_be,
        "loss_as_is_share": loss_as_is / annual_kwh(p),
        "saved_kwh": saved_kwh,
        "saved_share": saved_kwh / annual_kwh(p),
        "energy_eur": energy_eur,
        "labor_eur": labor_eur,
        "total_eur_year": total,
        "total_eur_month": total / 12,
        "price_share": p["price_hypothesis"] / (total / 12),
    }


def unit_variable_cost(p=P):
    parts = {
        "Обробка і зберігання показів": readings_per_month(p) / 1000 * p["cost_per_1000"],
        "Мобільний зв'язок шлюзу": p["sim_month"],
        "Платні сповіщення": p["alerts_month"] * p["alert_price"],
        "Підтримка": p["support_hours"] * p["support_rate"],
    }
    return parts, sum(parts.values())


def monthly_cost(n, p=P):
    return p["fixed_platform"] + unit_variable_cost(p)[1] * n


def average_cost(n, p=P):
    return monthly_cost(n, p) / n


