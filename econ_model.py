    name: str
    dod: str
    hours: dict
    preds: tuple
    o: float
    m: float
    p: float
    scope: str = ""
    p_note: str = ""

    @property
    def e(self):
        return (self.o + 4 * self.m + self.p) / 6

    @property
    def sigma(self):
        return (self.p - self.o) / 6

    @property
    def var(self):
        return self.sigma ** 2

    @property
    def effort_m(self):
        return sum(self.hours.values())

    @property
    def effort_e(self):
        return self.effort_m * self.e / self.m

    @property
    def lead(self):
        return max(self.hours, key=self.hours.get)


