def quadrant(s, threshold=4):
    high_influence = s.influence >= threshold
    high_interest = s.interest_level >= threshold
    if high_influence and high_interest:
        return "керувати тісно"
    if high_influence:
        return "задовольняти"
    if high_interest:
        return "інформувати"
    return "спостерігати"


def ranked_assumptions():
    return sorted(ASSUMPTIONS, key=lambda a: (-a.priority, -a.impact, int(a.aid[1:])))


def top_assumptions(n=5):
    return ranked_assumptions()[:n]


